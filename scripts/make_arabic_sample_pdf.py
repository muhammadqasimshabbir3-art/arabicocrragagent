def write_arabic_sample_pdf(path: Path) -> Path:
    """Create a multi-page Arabic PDF with extractable text."""
    import fitz

    path = path.resolve()
    path.parent.mkdir(parents=True, exist_ok=True)
    doc = fitz.open()
    for title, body in SAMPLE_PAGES:
        page = doc.new_page(width=595, height=842)  # A4
        html = f"""
        <div dir="rtl" style="font-family: sans-serif; font-size: 13pt; line-height: 1.7;">
          <h1 style="font-size: 18pt; color: #3d2a1a;">{title}</h1>
          <p style="white-space: pre-wrap;">{body.strip()}</p>
        </div>
        """
        page.insert_htmlbox(fitz.Rect(48, 48, 547, 794), html)
    doc.save(path)
    doc.close()
    return path


if __name__ == "__main__":
    out = Path(__file__).resolve().parents[1] / "data" / "samples" / "arabic_admin_circular.pdf"
    write_arabic_sample_pdf(out)
    print(f"Wrote {out}")
